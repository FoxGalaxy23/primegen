#!/usr/bin/env python3
"""Embed the Node WebAssembly RPC helper as a C string."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
src = root / 'mods/render/webpage/wasm_node_host.js'
dst = root / 'mods/render/webpage/wasm_node_host.h'
text = src.read_text(encoding='utf-8')
# Use a C raw string only where the compiler supports it? Keep portable C string literals instead.
lines = text.splitlines()
def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t').replace('\r', '')
out = ['/* Generated by tools/embed_wasm_host.py from wasm_node_host.js. */', '#ifndef MLB_WASM_NODE_HOST_H', '#define MLB_WASM_NODE_HOST_H', 'static const char *mlb_wasm_node_host_script =']
out += ['    "' + esc(line) + r'\n"' for line in lines]
out += ['    "\\n";', '#endif', '']
dst.write_text('\n'.join(out), encoding='utf-8')
print(f'embedded {len(lines)} lines -> {dst.relative_to(root)}')
