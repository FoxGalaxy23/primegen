void gal_clear(uint32_t color) {
    if (!back_buffer) return;
    for (int i = 0; i < SCREEN_WIDTH * SCREEN_HEIGHT; i++) back_buffer[i] = color;
}

void gal_put_pixel(int x, int y, uint32_t color) {
    if (back_buffer && x >= 0 && x < SCREEN_WIDTH && y >= 0 && y < SCREEN_HEIGHT) {
        back_buffer[y * SCREEN_WIDTH + x] = color;
    }
}

void gal_draw_rect(int x, int y, int w, int h, uint32_t color) {
    for (int i = y; i < y + h; i++) {
        for (int j = x; j < x + w; j++) gal_put_pixel(j, i, color);
    }
}

void gal_draw_char(int x, int y, char c, uint32_t color, int scale) {
    unsigned char uc = (unsigned char)c;
    if (uc < 32 || uc > 127) uc = 32;
    int idx = uc - 32;
    for (int row = 0; row < 8; row++) {
        uint8_t byte = font8x8[idx][row];
        for (int col = 0; col < 8; col++) {
            if (byte & (1 << (7 - col))) {
                gal_draw_rect(x + col * scale, y + row * scale, scale, scale, color);
            }
        }
    }
}

static uint32_t utf8_decode(const char** text) {
    const unsigned char* s = (const unsigned char*)*text;
    if (*s == 0) return 0;
    uint32_t c = *s++;
    if (c >= 0x80) {
        if ((c & 0xE0) == 0xC0 && s[0]) {
            c = ((c & 0x1F) << 6) | (*s++ & 0x3F);
        } else if ((c & 0xF0) == 0xE0 && s[0] && s[1]) {
            c = ((c & 0x0F) << 12) | ((s[0] & 0x3F) << 6) | (s[1] & 0x3F);
            s += 2;
        } else if ((c & 0xF8) == 0xF0 && s[0] && s[1] && s[2]) {
            c = ((c & 0x07) << 18) | ((s[0] & 0x3F) << 12) | ((s[1] & 0x3F) << 6) | (s[2] & 0x3F);
            s += 3;
        }
    }
    *text = (const char*)s;
    return c;
}

void gal_draw_string(int x, int y, const char* str, uint32_t color, int scale) {
#ifdef HAVE_RENDER
    if (g_ttf_font) {
        int font_size;
        switch (scale) {
            case 1:  font_size = 14; break;
            case 2:  font_size = 20; break;
            case 3:  font_size = 32; break;
            default: font_size = scale * 8; break;
        }
        gal_draw_ttf_string(x, y, str, color, font_size);
        return;
    }
#endif
    const char* ptr = str;
    while (*ptr) {
        uint32_t ch = utf8_decode(&ptr);
        gal_draw_char(x, y, (char)(ch < 128 ? ch : '?'), color, scale);
        x += 8 * scale;
    }
}

void gal_draw_ttf_string(int x, int y, const char* str, uint32_t color, int font_size) {
#ifdef HAVE_RENDER
    if (g_ttf_font) {
        ttf_render_string(g_ttf_font, str, back_buffer, SCREEN_WIDTH, SCREEN_HEIGHT,
                          font_size, x, y, color);
        return;
    }
#endif
    int scale = font_size / 8;
    if (scale < 1) scale = 1;
    const char* ptr = str;
    while (*ptr) {
        uint32_t ch = utf8_decode(&ptr);
        gal_draw_char(x, y, (char)(ch < 128 ? ch : '?'), color, scale);
        x += 8 * scale;
    }
}

int gal_ttf_text_width(const char* str, int font_size) {
#ifdef HAVE_RENDER
    if (g_ttf_font) {
        return ttf_text_width(g_ttf_font, str, font_size);
    }
#endif
    int scale = font_size / 8;
    if (scale < 1) scale = 1;
    return (int)strlen(str) * 8 * scale;
}

void gal_blit_image(int x, int y, int w, int h, const uint32_t* pixels) {
    if (!pixels || !back_buffer) return;
    for (int row = 0; row < h; row++) {
        int py = y + row;
        if (py < 0 || py >= SCREEN_HEIGHT) continue;
        for (int col = 0; col < w; col++) {
            int px = x + col;
            if (px < 0 || px >= SCREEN_WIDTH) continue;
            uint32_t src = pixels[row * w + col];
            uint8_t a = (src >> 24) & 0xFF;
            if (a == 255) {
                back_buffer[py * SCREEN_WIDTH + px] = src;
            } else if (a > 0) {
                uint32_t dst = back_buffer[py * SCREEN_WIDTH + px];
                uint8_t sr = (src >> 16) & 0xFF;
                uint8_t sg = (src >> 8) & 0xFF;
                uint8_t sb = src & 0xFF;
                uint8_t dr = (dst >> 16) & 0xFF;
                uint8_t dg = (dst >> 8) & 0xFF;
                uint8_t db = dst & 0xFF;
                uint8_t fr = (sr * a + dr * (255 - a)) / 255;
                uint8_t fg = (sg * a + dg * (255 - a)) / 255;
                uint8_t fb = (sb * a + db * (255 - a)) / 255;
                back_buffer[py * SCREEN_WIDTH + px] = (0xFF << 24) | (fr << 16) | (fg << 8) | fb;
            }
        }
    }
}

void gal_blit_image_scaled(int x, int y, int w, int h, const uint32_t* pixels, int src_w, int src_h) {
    if (!pixels || !back_buffer || w <= 0 || h <= 0 || src_w <= 0 || src_h <= 0) return;
    for (int row = 0; row < h; row++) {
        int py = y + row;
        if (py < 0 || py >= SCREEN_HEIGHT) continue;
        int sy = row * src_h / h;
        for (int col = 0; col < w; col++) {
            int px = x + col;
            if (px < 0 || px >= SCREEN_WIDTH) continue;
            int sx = col * src_w / w;
            uint32_t src = pixels[sy * src_w + sx];
            uint8_t a = (src >> 24) & 0xFF;
            if (a == 255) {
                back_buffer[py * SCREEN_WIDTH + px] = src;
            } else if (a > 0) {
                uint32_t dst = back_buffer[py * SCREEN_WIDTH + px];
                uint8_t sr = (src >> 16) & 0xFF;
                uint8_t sg = (src >> 8) & 0xFF;
                uint8_t sb = src & 0xFF;
                uint8_t dr = (dst >> 16) & 0xFF;
                uint8_t dg = (dst >> 8) & 0xFF;
                uint8_t db = dst & 0xFF;
                uint8_t fr = (sr * a + dr * (255 - a)) / 255;
                uint8_t fg = (sg * a + dg * (255 - a)) / 255;
                uint8_t fb = (sb * a + db * (255 - a)) / 255;
                back_buffer[py * SCREEN_WIDTH + px] = (0xFF << 24) | (fr << 16) | (fg << 8) | fb;
            }
        }
    }
}
